/**
 * Turn data/*.json into src/data.generated.ts so the data is compiled into
 * both the ESM and CommonJS builds (no runtime file reads, works in
 * browsers, bundlers, React Native, Deno and Bun).
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, listYears, readYear } from './lib/store.js';

const years = listYears();
if (years.length === 0) {
  console.error('No data/*.json files found. Run `npm run scrape` first.');
  process.exit(1);
}

const data: Record<number, unknown> = {};
let lastUpdated = '';
for (const y of years) {
  const file = readYear(y)!;
  data[y] = file;
  if (file.updatedAt > lastUpdated) lastUpdated = file.updatedAt;
}

const out = `// AUTO-GENERATED by scripts/build-data.ts from data/*.json — do not edit.
import type { YearData } from './type.js';

export const LAST_UPDATED = ${JSON.stringify(lastUpdated)};

export const DATA: Record<number, YearData> = ${JSON.stringify(data, null, 2)} as Record<number, YearData>;
`;

writeFileSync(join(ROOT, 'src', 'data.generated.ts'), out, 'utf8');
console.log(`data.generated.ts: years ${years.join(', ')} (last updated ${lastUpdated})`);